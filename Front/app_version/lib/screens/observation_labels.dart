String observationTime(DateTime? value) {
  if (value == null) return '미제공';
  final t = value.toUtc().add(const Duration(hours: 9));
  String two(int n) => n.toString().padLeft(2, '0');
  return '${t.year}-${two(t.month)}-${two(t.day)} ${two(t.hour)}:${two(t.minute)}:${two(t.second)} (한국)';
}
